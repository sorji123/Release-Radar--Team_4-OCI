"""Offline seed builder. Reads authored fixtures only; never reads expected.json.

Run from any directory: python database/demo/generate_seed.py
Only seed.sql beside this script is written. No Oracle connection or model calls.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent.parent / "data" / "demo"


def literal(value):
    if value is None:
        return "null"
    if isinstance(value, (float, int)):
        return str(value)
    # Small literals avoid SQL's 4000-byte literal limit and SQLcl substitution.
    parts = [value[i:i + 700] for i in range(0, len(value), 700)] or [""]
    return " || ".join("to_clob('" + p.replace("'", "''").replace("&", "' || chr(38) || '") + "')" for p in parts)


def scalar(value):
    return "'" + value.replace("'", "''") + "'"


def merge(table, row, keys, clobs=()):
    values = []
    for key, value in row.items():
        sql = literal(value) if key in clobs or value is None or isinstance(value, (float, int)) else scalar(value)
        values.append(f"{sql} as {key}")
    match = " and ".join(f"t.{k} = s.{k}" for k in keys)
    updates = ",\n    ".join(f"t.{k} = s.{k}" for k in row if k not in keys)
    return (f"merge into {table} t\nusing (select " + ",\n       ".join(values) + " from dual) s\n"
            f"on ({match})\nwhen matched then update set\n    {updates}\n"
            "when not matched then insert (" + ", ".join(row) + ")\nvalues (" + ", ".join(f"s.{k}" for k in row) + ");\n")


def main():
    read = lambda name: json.loads((DATA / name).read_text(encoding="utf-8"))
    objects, features = read("config_objects.json"), read("release_features.json")
    responses, vectors = read("responses.json"), read("embeddings.json")
    assert len(objects) == 6 and len(features) == 4
    sql = ["""-- Generated by generate_seed.py from authored SYNTHETIC fixtures.
-- SQL Workshop SQL Scripts compatible; no SQLcl directives here.
-- Requires the existing four baseline tables and two views. Re-runnable.
-- DDL commits implicitly; run installation in a dedicated session.
declare
    l_count number;
begin
    select count(*) into l_count from user_tables where table_name = 'RR_DEMO_RESPONSES';
    if l_count = 0 then
        execute immediate 'create table rr_demo_responses (
            release_code varchar2(10 char) not null,
            customer varchar2(100 char) not null,
            object_key varchar2(100 char) not null,
            feature_key varchar2(100 char) not null,
            distance number not null,
            response_json clob not null,
            constraint rr_demo_response_pk primary key (release_code, customer, object_key, feature_key),
            constraint rr_demo_response_scope_ck check
                (release_code = ''DEMO'' and customer = ''Northwind Telecom''),
            constraint rr_demo_response_dist_ck check (distance between 0 and 2),
            constraint rr_demo_response_json_ck check (response_json is json strict with unique keys),
            constraint rr_demo_response_obj_fk foreign key (customer, object_key)
                references config_objects (customer, object_key),
            constraint rr_demo_response_feat_fk foreign key (release_code, feature_key)
                references release_features (release_code, feature_key)
        )';
    end if;
end;
/

begin
"""]
    for obj in objects:
        assert obj["customer"] == "Northwind Telecom"
        sql.append(merge("config_objects", {**obj, "embedding": None}, ("customer", "object_key"), ("description", "snippet")))
    for feature in features:
        assert feature["release_code"] == "DEMO" and feature["source_kind"] == "SYNTHETIC"
        sql.append(merge("release_features", {**feature, "embedding": None}, ("release_code", "feature_key"), ("description",)))
    pairs = responses["Northwind Telecom"]["DEMO"]
    assert len(pairs) == 4
    for pair, response in pairs.items():
        object_key, feature_key = pair.split("|")
        a, b = vectors["objects"]["Northwind Telecom"][object_key], vectors["features"]["DEMO"][feature_key]
        distance = round(1 - sum(x * y for x, y in zip(a, b)) / (math.hypot(*a) * math.hypot(*b)), 8)
        row = dict(release_code="DEMO", customer="Northwind Telecom", object_key=object_key,
                   feature_key=feature_key, distance=distance,
                   response_json=json.dumps(response, ensure_ascii=True, separators=(",", ":")))
        sql.append(merge("rr_demo_responses", row, ("release_code", "customer", "object_key", "feature_key"), ("response_json",)))
    sql.append("    commit;\nexception when others then\n    rollback;\n    raise;\nend;\n/\n")
    (HERE / "seed.sql").write_text("\n".join(sql), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
