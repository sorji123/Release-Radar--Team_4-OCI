"""Build APEX-compatible browser assets and serve a local, read-only preview."""

import json
import re
import time
from datetime import datetime, timezone
from functools import partial
from html.parser import HTMLParser
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse
from urllib.request import Request, urlopen
from zipfile import ZipFile, ZIP_DEFLATED

from .pipeline import ROOT

NEWS_URL = "https://docs.oracle.com/en/cloud/saas/readiness/news.html"
ASSETS = ("rr-core.js", "rr-data.js", "rr-app.js", "rr-style.css", "icon.svg")


def build_site(root: Path = ROOT) -> Path:
    """Keep the committed browser payload reproducible from reviewed source data."""
    catalog = json.loads((root / "data/releases/26D.json").read_text(encoding="utf-8"))
    sample = json.loads((root / "config/fusion-customizations.example.json").read_text(encoding="utf-8"))
    if not re.fullmatch(r"\d{2}[A-D]", catalog["release_code"]):
        raise ValueError("Invalid release code")
    datetime.strptime(catalog["verified_on"], "%Y-%m-%d")
    seen = set()
    for feature in catalog["features"]:
        if feature["id"] in seen:
            raise ValueError("Duplicate release feature")
        seen.add(feature["id"])
        url = urlparse(feature["source_url"])
        if url.scheme != "https" or url.hostname != "docs.oracle.com" or not url.path.startswith("/en/cloud/saas/readiness/"):
            raise ValueError("Catalog sources must use Oracle readiness documentation")
        if f"/{catalog['release_code'].lower()}/" not in url.path:
            raise ValueError("Source release does not match the catalog")
        if feature["category"] not in {"REVIEW", "TEST", "OPPORTUNITY"}:
            raise ValueError("Invalid review category")
        if not feature["quote"] or len(feature["quote"].split()) > 25:
            raise ValueError("Use a short source excerpt of at most 25 words")
        if not feature["match_groups"] or any(not group for group in feature["match_groups"]):
            raise ValueError("Each feature requires explicit matching terms")
    payload = "// Generated by python -m release_radar build-site. Edit data/releases or config instead.\n"
    for name, value in (("RR_RELEASE_CATALOG", catalog), ("RR_SAMPLE_CONFIG", sample)):
        payload += f"globalThis.{name} = " + json.dumps(value, ensure_ascii=False, indent=2) + ";\n"
    output = root / "web/rr-data.js"
    output.write_text(payload, encoding="utf-8")
    bundle = root / "build/release-radar-apex-assets.zip"
    bundle.parent.mkdir(exist_ok=True)
    with ZipFile(bundle, "w", ZIP_DEFLATED) as archive:
        for name in ASSETS:
            archive.write(root / "web" / name, name)
    return bundle


class ReadinessParser(HTMLParser):
    """Inspect the current announcements, excluding the past-revisions section."""

    def __init__(self):
        super().__init__()
        self.heading = None
        self.heading_text = []
        self.current = False
        self.releases = set()
        self.link = None

    def handle_starttag(self, tag, attrs):
        if tag == "h2":
            self.heading = tag
            self.heading_text = []
        if tag == "a":
            self.link = dict(attrs).get("href", "")

    def handle_data(self, data):
        if self.heading:
            self.heading_text.append(data)
        if self.current and self.link:
            self.releases.update(re.findall(r"\b(\d{2}[A-D])\b", data))

    def handle_endtag(self, tag):
        if tag == "h2" and self.heading:
            self.current = "features introduced" in " ".join(self.heading_text).lower()
            self.heading = None
        if tag == "a":
            self.link = None


def check_latest(fetch=None) -> dict:
    """No customer data is sent; this retrieves one public Oracle index page."""
    if fetch is None:
        def fetch():
            request = Request(NEWS_URL, headers={"User-Agent": "ReleaseRadar/0.2 readiness-check"})
            with urlopen(request, timeout=8) as response:
                if urlparse(response.geturl()).hostname != "docs.oracle.com":
                    raise ValueError("Unexpected readiness redirect")
                return response.read(2_000_000).decode("utf-8")
    parser = ReadinessParser()
    parser.feed(fetch())
    if not parser.releases:
        raise ValueError("Oracle's current release could not be identified. Review the readiness page manually.")
    return {"latest_release": max(parser.releases, key=lambda r: (int(r[:2]), r[2])),
            "checked_at": datetime.now(timezone.utc).isoformat(), "source_url": NEWS_URL}


class SiteHandler(SimpleHTTPRequestHandler):
    # Preview serves only public UI assets; never the repository, credentials or uploads.
    readiness_cache = None
    readiness_time = 0.0

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/api/release-status":
            try:
                if time.monotonic() - type(self).readiness_time > 300 or type(self).readiness_cache is None:
                    type(self).readiness_cache = check_latest()
                    type(self).readiness_time = time.monotonic()
                data, status = type(self).readiness_cache, 200
            except Exception:
                data, status = {"error": "Oracle's live readiness check is unavailable. The dated review catalog is still available.", "source_url": NEWS_URL}, 503
            payload = json.dumps(data).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(payload)))
            self.end_headers()
            self.wfile.write(payload)
            return
        if path not in {"/", "/index.html", *("/" + name for name in ASSETS)}:
            self.send_error(404)
            return
        super().do_GET()

    def do_HEAD(self):
        if urlparse(self.path).path not in {"/", "/index.html", *("/" + name for name in ASSETS)}:
            self.send_error(404)
            return
        super().do_HEAD()

    def end_headers(self):
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        super().end_headers()


def serve_site(port: int = 8765) -> None:
    build_site()
    handler = partial(SiteHandler, directory=str(ROOT / "web"))
    server = ThreadingHTTPServer(("127.0.0.1", port), handler)
    print(f"Release Radar: http://127.0.0.1:{port} (Ctrl+C to stop)", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
